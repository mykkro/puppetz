// Writes models/humanoid.schema.json (the JSON Schema for humanoid recipes) from the generator's
// option and item tables, so the allowed item names always match src/rig/items.js.
// Usage: npm run build:schema
import { writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { BODY_OPTIONS, EXPRESSIONS, SLOTS, itemsForSlot } from '../src/rig/humanoid.js';
import { TEXTURE_TYPES } from '../src/rig/textures.js';

const color = { type: 'string', pattern: '^#[0-9a-fA-F]{6}$' };
const body = Object.fromEntries(BODY_OPTIONS.map((o) => [o.key, o.options ? { enum: o.options, description: o.label }
  : o.range ? { type: 'number', minimum: o.range[0], maximum: o.range[1], description: o.label }
  : { ...color, description: o.label }]));
const slot = (key, label) => {
  const ids = itemsForSlot(key).map((i) => i.id);
  return {
    description: `${label}: ${ids.join(', ')}. A name, or { item, color, accent } to recolor it.`,
    oneOf: [
      { enum: [...ids, 'none'] },
      { type: 'object', required: ['item'], additionalProperties: false,
        properties: { item: { enum: ids }, color, accent: color } },
    ],
  };
};

const schema = {
  $schema: 'https://json-schema.org/draft/2020-12/schema',
  $id: 'humanoid.schema.json',
  title: 'Puppetz humanoid recipe',
  description: 'A generated humanoid: body settings plus items in slots. Generated by tools/build-humanoid-schema.mjs; see docs/humanoids.md.',
  type: 'object',
  required: ['generator', 'id'],
  additionalProperties: false,
  properties: {
    $schema: { type: 'string' },
    generator: { const: 'humanoid' },
    id: { type: 'string', pattern: '^[A-Za-z0-9_-]+$' },
    name: { type: 'string' },
    description: { type: 'string' },
    version: { type: 'integer', minimum: 1 },
    body: { type: 'object', additionalProperties: false, properties: body },
    equipment: { type: 'object', additionalProperties: false, properties: Object.fromEntries(SLOTS.map((s) => [s.key, slot(s.key, s.label)])) },
    expression: { enum: EXPRESSIONS, description: 'Expression the character starts with.' },
    textures: { type: 'boolean', default: true, description: 'false: flat colors, no procedural textures.' },
    materials: {
      type: 'object',
      description: 'Per-material overrides by material name (skin, clothes, armor_metal, cape...), e.g. a different texture or roughness.',
      additionalProperties: {
        type: 'object',
        properties: {
          color, roughness: { type: 'number' }, metalness: { type: 'number' },
          texture: { enum: TEXTURE_TYPES }, textureScale: { type: 'number' }, textureStrength: { type: 'number' }, bumpScale: { type: 'number' },
        },
      },
    },
  },
};

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'models', 'humanoid.schema.json');
await writeFile(out, `${JSON.stringify(schema, null, 2)}\n`);
console.log(`✔ ${out}`);
